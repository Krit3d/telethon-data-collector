def canonicalize_city(val: str | None) -> str | None:
    if val is None or not isinstance(val, str):
        return None
    cleaned = val.strip().strip("\"'«»")
    if not cleaned:
        return None
    lower_val = cleaned.lower()
    for prefix in ("город ", "г. ", "г.", "г "):
        if lower_val.startswith(prefix):
            cleaned = cleaned[len(prefix):].strip()
            lower_val = cleaned.lower()
            break
    if not cleaned:
        return None
    if lower_val in CITY_ALIASES:
        return CITY_ALIASES[lower_val]
    parts = cleaned.split("-")
    capitalized_parts = [
        " ".join(word.capitalize() for word in part.split())
        for part in parts
    ]
    return "-".join(capitalized_parts)